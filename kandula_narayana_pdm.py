def compute_metrics(model, X, y, threshold=0.5):
    """All evaluation metrics for one model on one dataset (decisions use the given probability threshold)."""
    probability = model.predict_proba(X[FEATURES])[:, 1]
    decision = (probability >= threshold).astype(int)
    return {'Log loss': log_loss(y, probability), 'Brier score': brier_score_loss(y, probability),
            'Accuracy': accuracy_score(y, decision), 'Balanced accuracy': balanced_accuracy_score(y, decision),
            'Precision': precision_score(y, decision, zero_division=0), 'Recall': recall_score(y, decision, zero_division=0),
            'F1 score': f1_score(y, decision, zero_division=0), 'ROC AUC': roc_auc_score(y, probability),
            'PR AUC': average_precision_score(y, probability), 'Matthews correlation': matthews_corrcoef(y, decision)}


