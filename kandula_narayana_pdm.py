def _menu_position(fig):
    """Return the paper y-coordinate just above the plotting area, used to place dropdowns."""
    plot_height = fig.layout.height - fig.layout.margin.t - fig.layout.margin.b
    return 1 + 42 / plot_height, 1 + 78 / plot_height


def _add_menu(fig, buttons, label, x, active):
    y_menu, y_label = _menu_position(fig)
    menu = dict(type='dropdown', buttons=buttons, active=active, x=x, xanchor='left',
                y=y_menu, yanchor='bottom', showactive=True, bgcolor='#F8F9FA',
                bordercolor='#ADB5BD', font=dict(size=12))
    fig.update_layout(updatemenus=list(fig.layout.updatemenus) + [menu])
    fig.add_annotation(text=f'<b>{label}</b>', x=x, y=y_label, xref='paper', yref='paper',
                       xanchor='left', yanchor='bottom', showarrow=False, font=dict(size=12, color='#495057'))


def add_cmap_dropdown(fig, attr='colorscale', trace_ids=None, initial='Viridis', x=0.0):
    """Add an interactive colour map dropdown.

    attr      : the Plotly attribute that holds the colour scale ('colorscale' for heatmaps,
                'marker.colorscale' for bars and scatter points)
    trace_ids : which traces the dropdown controls (default: all traces)
    initial   : the colour map the figure starts with (it must also be set on the traces)
    """
    ids = list(range(len(fig.data))) if trace_ids is None else list(trace_ids)
    buttons = [dict(label=name, method='restyle', args=[{attr: name}, ids]) for name in CMAPS]
    _add_menu(fig, buttons, 'Colour map', x, CMAPS.index(initial))


def add_palette_dropdown(fig, trace_ids, x=0.0, groups=None, line=False):
    """Add an interactive dropdown that swaps the colour combination of categorical traces.

    The first option restores the original, meaningful colours.
    groups : optional list with one group number per trace, so traces in different subplots that
             represent the same category receive the same colour (default: one colour per trace).
    line   : set to True for line traces, so the line colour changes as well as the marker colour.
    Only traces whose colour is a single colour (not an array) are supported.
    """
    ids = list(trace_ids)
    groups = list(groups) if groups is not None else list(range(len(ids)))
    original = {'marker.color': [fig.data[i].marker.color for i in ids]}
    if line:
        original['line.color'] = [fig.data[i].line.color for i in ids]
    buttons = [dict(label='Original colours', method='restyle', args=[original, ids])]
    for name, colours in PALETTES.items():
        chosen = [colours[g % len(colours)] for g in groups]
        change = {'marker.color': chosen}
        if line:
            change['line.color'] = chosen
        buttons.append(dict(label=name, method='restyle', args=[change, ids]))
    _add_menu(fig, buttons, 'Colour combination', x, 0)


def value_bar(labels, values, title, subtitle=None, axis_title='Count', text=None,
              horizontal=False, height=520, value_format=',.0f', hover_unit='', colour_range=None, text_inside=False):
    """Labelled bar chart coloured by value, with an interactive colour map dropdown."""
    labels, values = list(labels), list(values)
    text = text if text is not None else [format(v, value_format) for v in values]
    marker = dict(color=values, colorscale='Viridis', showscale=True,
                  colorbar=dict(title=axis_title), line=dict(color='white', width=1))
    if colour_range:
        marker.update(cmin=colour_range[0], cmax=colour_range[1])
    position = 'inside' if text_inside else 'outside'
    if horizontal:
        trace = go.Bar(y=labels, x=values, orientation='h', text=text, textposition=position, insidetextanchor='start',
                       marker=marker, cliponaxis=False,
                       hovertemplate='%{y}<br>%{x:,.2f}' + hover_unit + '<extra></extra>')
    else:
        trace = go.Bar(x=labels, y=values, text=text, textposition=position,
                       marker=marker, cliponaxis=False,
                       hovertemplate='%{x}<br>%{y:,.2f}' + hover_unit + '<extra></extra>')
    fig = go.Figure(trace)
    style_figure(fig, title, subtitle, height)
    if horizontal:
        fig.update_xaxes(title=axis_title)
        fig.update_yaxes(autorange='reversed')
    else:
        fig.update_yaxes(title=axis_title)
    add_cmap_dropdown(fig, 'marker.colorscale')
    return fig


def plotly_table(df, title, status_col=None, height=None, decimals=3, col_widths=None):
    """Colour-coded interactive table. A status column is shaded green, amber or red."""
    d = df.copy()
    for c in d.columns:
        if pd.api.types.is_float_dtype(d[c]):
            whole = d[c].dropna().apply(lambda v: float(v).is_integer()).all() if d[c].notna().any() else False
            d[c] = d[c].map(lambda v: '' if pd.isna(v) else (f'{v:,.0f}' if whole else f'{v:,.{decimals}f}'))
    n = len(d)
    stripe = ['#F1FAEE' if i % 2 == 0 else '#E3EEF2' for i in range(n)]
    fills = [stripe[:] for _ in d.columns]
    if status_col and status_col in d.columns:
        palette = {'pass': '#B7E4C7', 'match': '#B7E4C7', 'yes': '#B7E4C7', 'best': '#B7E4C7',
                   'attention': '#FFE8A3', 'review': '#FFE8A3', 'flag': '#FFE8A3', 'caution': '#FFE8A3',
                   'fail': '#F4A6A6', 'check': '#F4A6A6', 'no': '#EDEDED'}
        position = list(d.columns).index(status_col)
        fills[position] = [palette.get(str(v).lower().split()[0], stripe[i]) if str(v) else stripe[i]
                           for i, v in enumerate(d[status_col])]
    fig = go.Figure(go.Table(
        columnwidth=col_widths,
        header=dict(values=[f'<b>{c}</b>' for c in d.columns], fill_color='#264653',
                    font=dict(color='white', size=13), align='left', height=34),
        cells=dict(values=[d[c].astype(str).tolist() for c in d.columns], fill_color=fills,
                   font=dict(color='#1D3557', size=12), align='left', height=28)))
    fig.update_layout(template='plotly_white', title=dict(text=f'<b>{title}</b>', x=0.01),
                      height=height or min(110 + 30 * n, 760), margin=dict(t=70, l=20, r=20, b=20),
                      font=dict(family='Arial, sans-serif'))
    return fig


