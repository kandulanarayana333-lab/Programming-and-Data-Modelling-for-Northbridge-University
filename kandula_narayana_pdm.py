class FairnessAuditor:
    """Group-level fairness measures for a set of predictions."""

    def __init__(self, data, y_true, probability, shortlisted, attributes, min_group_size=200):
        self.frame = data[list(attributes)].copy()
        self.frame['actual'] = np.asarray(y_true)
        self.frame['probability'] = np.asarray(probability)
        self.frame['shortlisted'] = np.asarray(shortlisted).astype(int)
        self.attributes = attributes
        self.min_group_size = min_group_size

    def group_table(self):
        rows = []
        for attribute, label in self.attributes.items():
            part_table = []
            for level, part in self.frame.groupby(attribute):
                positives, negatives = part['actual'] == 1, part['actual'] == 0
                part_table.append({'Characteristic': label, 'Group': str(level), 'Applicants': len(part),
                                   'Historical offer rate': part['actual'].mean(), 'Mean predicted probability': part['probability'].mean(),
                                   'Shortlist rate': part['shortlisted'].mean(),
                                   'True positive rate': part.loc[positives, 'shortlisted'].mean(),
                                   'False positive rate': part.loc[negatives, 'shortlisted'].mean()})
            table = pd.DataFrame(part_table)
            reference = table.loc[table['Applicants'].idxmax()]
            table['Reference group'] = reference['Group']
            table['Disparate impact ratio'] = table['Shortlist rate'] / reference['Shortlist rate']
            table['Shortlist rate gap (points)'] = (table['Shortlist rate'] - reference['Shortlist rate']) * 100
            table['True positive rate gap (points)'] = (table['True positive rate'] - reference['True positive rate']) * 100
            outside = (table['Disparate impact ratio'] < 0.8) | (table['Disparate impact ratio'] > 1.25)
            table['Status'] = np.where(table['Applicants'] < self.min_group_size, 'Caution',
                                       np.where(outside, 'Flag', 'Pass'))
            rows.append(table)
        return pd.concat(rows, ignore_index=True)

    def attribute_summary(self, table):
        rows = []
        for attribute, label in self.attributes.items():
            part = table[table['Characteristic'] == label]
            contingency = pd.crosstab(self.frame[attribute], self.frame['shortlisted'])
            p_value = chi2_contingency(contingency)[1]
            comparable = part[part['Applicants'] >= self.min_group_size]
            worst = comparable.loc[(comparable['Disparate impact ratio'] - 1).abs().idxmax()]
            rows.append({'Characteristic': label, 'Reference group': part['Reference group'].iloc[0],
                         'Group furthest from parity': worst['Group'], 'Disparate impact ratio': worst['Disparate impact ratio'],
                         'Shortlist rate gap (points)': worst['Shortlist rate gap (points)'], 'Chi-square p-value': p_value,
                         'Status': 'Flag' if (part['Status'] == 'Flag').any() else 'Pass'})
        return pd.DataFrame(rows)


