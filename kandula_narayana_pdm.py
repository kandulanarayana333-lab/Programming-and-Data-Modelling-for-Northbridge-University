"""## Clean the admission data

All cleaning is done by the `AdmissionsCleaner` class so that the same rules can be reused and maintained. **Every change is written to a cleaning log**, and every affected row receives a `cleaning_flags` entry, so nothing is changed silently.

| Issue | Treatment | Reason |
|---|---|---|
| Whitespace and inconsistent case | Trimmed and mapped to the accepted label | Prevents the same category appearing under several names |
| Abbreviated labels such as `S`, `Soc`, `A`, `M`, `F`, `Mental` | Mapped to the full accepted label | Each abbreviation has only one possible meaning |
| Ambiguous code `I` in `school_type` | Set to missing, then imputed | It could mean Independent or International, and guessing would add bias |
| Duplicate IDs or duplicate records | Removed (first record kept) | Duplicates would double-count applicants |
| Scores outside their scale | Capped at the scale limits | Values such as 105.7 on a 0 to 100 scale are impossible |
| Extreme distances beyond three interquartile ranges | Capped at that fence | Keeps genuine long distances while limiting distortion |
| Missing numeric values | Median of the combined data | Robust to skew and outliers |
| Missing categories | Most frequent category | Only a handful of cells are affected |
| Missing disability status | Category `Not Recorded` | Avoids asserting that an applicant has no disability when this is unknown |

The medians and modes affect only a handful of cells, so the leakage from computing them before the train and test split is negligible. The model pipeline itself learns scaling and encoding on the training data only.
"""

class AdmissionsCleaner:
    """Apply documented cleaning rules to the combined recruiter data and keep an audit trail."""

    LABEL_ABBREVIATIONS = {
        'school_type': {'s': 'State'},
        'intended_subject_area': {'a': 'Arts', 'soc': 'Social Sciences'},
        'gender': {'m': 'Male', 'f': 'Female'},
        'disability_status': {'mental': 'Mental Health'},
    }
    # Codes that could mean more than one label are never guessed
    AMBIGUOUS_CODES = {'school_type': ['i']}

    def __init__(self, extreme_iqr_multiplier=3.0):
        self.extreme_iqr_multiplier = extreme_iqr_multiplier
        self.log = []
        self.fill_values = {}

    def _record(self, step, column, issue, rows, action, rationale):
        if rows:
            self.log.append({'Step': step, 'Column': column, 'Issue found': issue,
                             'Rows affected': int(rows), 'Action taken': action, 'Rationale': rationale})

    @staticmethod
    def _flag(flags, mask, text):
        updated = flags.copy()
        updated.loc[mask] = updated.loc[mask].map(lambda s: f'{s};{text}' if s else text)
        return updated

    def _lookup(self, column):
        canonical = {label.lower(): label for label in ALLOWED_VALUES[column]}
        return {**canonical, **self.LABEL_ABBREVIATIONS.get(column, {})}

    def clean(self, raw):
        self.log = []
        df = raw.copy()
        flags = pd.Series('', index=df.index, dtype=object)

        # Text hygiene: trim leading and trailing spaces
        for column in TEXT_COLUMNS:
            before = df[column]
            after = before.str.strip()
            changed = before.notna() & (before != after)
            self._record('Text hygiene', column, 'Leading or trailing spaces', changed.sum(), 'Trimmed',
                         'Spaces create false categories')
            df[column] = after

        # Numeric coercion: anything that is not a number becomes missing and is treated later
        for column in NUMERIC_COLUMNS:
            before = df[column]
            after = pd.to_numeric(before, errors='coerce')
            lost = before.notna() & after.isna()
            self._record('Numeric conversion', column, 'Non-numeric text in a numeric column', lost.sum(),
                         'Converted to missing', 'Cannot be interpreted as a number')
            df[column] = after.astype(float)

        # Label standardisation
        for column in CATEGORICAL_COLUMNS:
            original = df[column]
            key = original.str.lower()
            standard = key.map(self._lookup(column))
            ambiguous = key.isin(self.AMBIGUOUS_CODES.get(column, []))
            unrecognised = original.notna() & standard.isna() & ~ambiguous
            relabelled = original.notna() & standard.notna() & (original != standard)
            examples = ', '.join(sorted(original[relabelled].astype(str).unique())[:6])
            self._record('Label standardisation', column, f'Non-standard labels ({examples})', relabelled.sum(),
                         'Mapped to the accepted label', 'Each variant has a single possible meaning')
            self._record('Label standardisation', column, 'Ambiguous code', ambiguous.sum(),
                         'Set to missing (imputed later)', 'The code could mean more than one category')
            self._record('Label standardisation', column, 'Unrecognised label', unrecognised.sum(),
                         'Set to missing (imputed later)', 'Not in the data dictionary')
            flags = self._flag(flags, relabelled, f'relabelled:{column}')
            flags = self._flag(flags, ambiguous | unrecognised, f'label_to_missing:{column}')
            df[column] = standard

        # Duplicates: repeated IDs, then repeated records under different IDs
        duplicate_ids = df['student_id'].duplicated(keep='first')
        self._record('Duplicates', 'student_id', 'Repeated student ID', duplicate_ids.sum(),
                     'Removed, first record kept', 'An applicant must appear once')
        df, flags = df.loc[~duplicate_ids], flags.loc[~duplicate_ids]
        content_columns = [c for c in EXPECTED_COLUMNS if c != 'student_id']
        duplicate_records = df.duplicated(subset=content_columns, keep='first')
        self._record('Duplicates', 'all columns', 'Identical record under a different ID', duplicate_records.sum(),
                     'Removed, first record kept', 'Likely the same applicant submitted twice')
        df, flags = df.loc[~duplicate_records], flags.loc[~duplicate_records]

        # Target and binary fields must be 0 or 1
        invalid_target = df[TARGET].isna() | ~df[TARGET].isin([0, 1])
        self._record('Target validation', TARGET, 'Missing or invalid outcome', invalid_target.sum(),
                     'Row removed', 'A model cannot learn from or be judged on an unknown outcome')
        df, flags = df.loc[~invalid_target], flags.loc[~invalid_target]
        invalid_binary = df['first_generation_student'].notna() & ~df['first_generation_student'].isin([0, 1])
        self._record('Binary validation', 'first_generation_student', 'Value other than 0 or 1', invalid_binary.sum(),
                     'Set to missing (imputed later)', 'Outside the accepted values')
        if invalid_binary.any():
            df.loc[invalid_binary, 'first_generation_student'] = np.nan

        # Impossible values: scores outside their scale
        for column, (low, high) in SCORE_LIMITS.items():
            below, above = df[column] < low, df[column] > high
            self._record('Range correction', column, f'Below the scale minimum of {low}', below.sum(),
                         f'Raised to {low}', 'Impossible value on the documented scale')
            self._record('Range correction', column, f'Above the scale maximum of {high}', above.sum(),
                         f'Lowered to {high}', 'Impossible value on the documented scale')
            flags = self._flag(flags, below | above, f'score_capped:{column}')
            df[column] = df[column].clip(low, high)

        # Distance: negative values are impossible, extreme values are capped at an IQR fence
        negative = df['distance_from_campus_km'] < 0
        self._record('Range correction', 'distance_from_campus_km', 'Negative distance', negative.sum(),
                     'Set to missing (imputed later)', 'A distance cannot be negative')
        df.loc[negative, 'distance_from_campus_km'] = np.nan
        q1, q3 = df['distance_from_campus_km'].quantile([0.25, 0.75])
        self.distance_fence = q3 + self.extreme_iqr_multiplier * (q3 - q1)
        extreme = df['distance_from_campus_km'] > self.distance_fence
        self._record('Outlier treatment', 'distance_from_campus_km',
                     f'Extreme distance above {self.distance_fence:,.1f} km ({self.extreme_iqr_multiplier} IQR fence)',
                     extreme.sum(), f'Capped at {self.distance_fence:,.1f} km',
                     'Keeps long but plausible distances while limiting distortion')
        flags = self._flag(flags, extreme, 'distance_capped')
        df['distance_from_campus_km'] = df['distance_from_campus_km'].clip(upper=self.distance_fence)

        # Imputation of any remaining missing values
        numeric_to_impute = SCORE_COLUMNS + ['distance_from_campus_km']
        for column in numeric_to_impute:
            missing = df[column].isna()
            if missing.any():
                value = float(df[column].median())
                self.fill_values[column] = value
                self._record('Imputation', column, 'Missing value', missing.sum(),
                             f'Filled with the median ({value:,.2f})', 'Median is robust to skew')
                flags = self._flag(flags, missing, f'imputed:{column}')
                df.loc[missing, column] = value
        for column in ['school_type', 'intended_subject_area', 'gender', 'ethnicity']:
            missing = df[column].isna()
            if missing.any():
                value = df[column].mode().iloc[0]
                self.fill_values[column] = value
                self._record('Imputation', column, 'Missing or ambiguous label', missing.sum(),
                             f"Filled with the most frequent category ('{value}')", 'Only a handful of cells affected')
                flags = self._flag(flags, missing, f'imputed:{column}')
                df.loc[missing, column] = value
        missing = df['disability_status'].isna()
        self._record('Imputation', 'disability_status', 'Missing value', missing.sum(),
                     "Filled with the category 'Not Recorded'",
                     'Avoids claiming that an applicant has no disability when this is unknown')
        flags = self._flag(flags, missing, 'imputed:disability_status')
        df.loc[missing, 'disability_status'] = 'Not Recorded'
        missing = df['first_generation_student'].isna()
        if missing.any():
            value = int(df['first_generation_student'].mode().iloc[0])
            self._record('Imputation', 'first_generation_student', 'Missing value', missing.sum(),
                         f'Filled with the most frequent value ({value})', 'Only a handful of cells affected')
            flags = self._flag(flags, missing, 'imputed:first_generation_student')
            df.loc[missing, 'first_generation_student'] = value

        # Final types, flags and index
        df['first_generation_student'] = df['first_generation_student'].astype(int)
        df[TARGET] = df[TARGET].astype(int)
        df['cleaning_flags'] = flags.loc[df.index]
        ordered = ['student_id', 'recruiter'] + [c for c in EXPECTED_COLUMNS if c != 'student_id'] + ['cleaning_flags']
        df = df[ordered].set_index('student_id', verify_integrity=True).sort_index()
        return df

    def log_frame(self):
        return pd.DataFrame(self.log, columns=['Step', 'Column', 'Issue found', 'Rows affected',
                                               'Action taken', 'Rationale'])


