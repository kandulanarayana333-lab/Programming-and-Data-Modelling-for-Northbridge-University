def validate_dataset(df, extra_allowed=None):
    """Run the validation checks and return a tidy table of results."""
    d = df.reset_index() if df.index.name == 'student_id' else df.copy()
    extra_allowed = extra_allowed or {}
    results = []

    def add(check, failed, detail=''):
        results.append({'Check': check, 'Failed rows': int(failed),
                        'Status': 'Pass' if failed == 0 else 'Attention', 'Detail': detail})

    missing_columns = sorted(set(EXPECTED_COLUMNS) - set(d.columns))
    add('All expected columns are present', len(missing_columns), ', '.join(missing_columns))
    add('student_id values are unique', d['student_id'].duplicated().sum())
    add('student_id has one letter followed by five digits',
        (~d['student_id'].astype(str).str.match(r'^[A-Za-z]\d{5}$')).sum())
    add('student_id prefix agrees with the recruiter',
        (d['student_id'].str[0].str.upper() != d['recruiter'].str[-1]).sum())

    for column, allowed in ALLOWED_VALUES.items():
        permitted = allowed + extra_allowed.get(column, [])
        bad = d[column].notna() & ~d[column].isin(permitted)
        detail = ', '.join(sorted(d.loc[bad, column].astype(str).unique())[:8])
        add(f'{column} uses only accepted labels', bad.sum(), detail)

    for column, (low, high) in SCORE_LIMITS.items():
        bad = d[column].notna() & ((d[column] < low) | (d[column] > high))
        add(f'{column} lies between {low} and {high}', bad.sum())
    add('distance_from_campus_km is not negative', (d['distance_from_campus_km'] < 0).sum())
    for column in ['first_generation_student', TARGET]:
        add(f'{column} contains only 0 or 1', (d[column].notna() & ~d[column].isin([0, 1])).sum())

    add('No missing cells in the twelve data columns', d[EXPECTED_COLUMNS].isna().sum().sum())
    return pd.DataFrame(results)


