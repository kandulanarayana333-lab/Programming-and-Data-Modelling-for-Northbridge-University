"""## Fairness audit

Good overall accuracy says nothing about whether the model treats groups fairly, so the predictions are audited for every protected group and for the two named proxy variables (school type and distance from campus).

**How the audit works**
- Each applicant receives an **out-of-fold prediction**: five-fold cross-validation over all 8,000 applicants, so every prediction comes from a model that never saw that applicant. This also gives the small groups enough applicants to measure.
- The shortlist is **capacity matched**: the top share of applicants by predicted probability equal to the historical offer rate is shortlisted. A fixed 0.5 cut-off would shortlist almost everyone and hide any difference.
- Each group is compared with the **largest group** of its characteristic (the reference group).

**Measures**
- **Shortlist rate**: share of the group that the model would shortlist
- **Disparate impact ratio**: group shortlist rate divided by the reference group rate. The four-fifths rule treats a ratio outside **0.80 to 1.25** as a warning sign
- **True positive rate**: among applicants who historically received an offer, the share the model would shortlist (equal opportunity)
- **False positive rate**: among applicants who did not receive an offer, the share the model would shortlist
- Groups with fewer than 200 applicants are marked **Caution** because their rates are statistically noisy

One applicant whose disability status was not recorded is excluded from the audit.
"""

