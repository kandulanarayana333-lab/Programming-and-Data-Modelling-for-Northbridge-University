"""## Proxy variable audit

Removing protected characteristics does not guarantee fairness, because the remaining variables may still **encode** them. Two checks are run before any model is trained.

- **Association strength.** How strongly is each allowed or proxy-risk variable associated with each protected characteristic? Cramer's V is used for two categorical variables and the correlation ratio (eta) for a numeric variable against a category. Both run from 0 (no association) to 1 (perfect association).
- **Predictability.** Can a simple model **predict** each protected characteristic from the variables? A cross-validated ROC AUC of 0.50 is chance level, meaning no proxy signal. Values well above 0.50 would show that the variables reveal the protected characteristic.
"""

def cramers_v_between(a, b):
    """Bias-corrected Cramer's V between two categorical series."""
    table = pd.crosstab(a, b)
    chi2 = chi2_contingency(table, correction=False)[0]
    n = table.values.sum()
    r, k = table.shape
    phi2 = max(0, chi2 / n - (k - 1) * (r - 1) / (n - 1))
    r_corr, k_corr = r - (r - 1) ** 2 / (n - 1), k - (k - 1) ** 2 / (n - 1)
    denominator = min(k_corr - 1, r_corr - 1)
    return math.sqrt(phi2 / denominator) if denominator > 0 else 0.0


def correlation_ratio(categories, values):
    """Correlation ratio (eta): how much of a numeric variable's variance is explained by a category."""
    overall = values.mean()
    between = sum(len(g) * (g.mean() - overall) ** 2 for _, g in values.groupby(categories))
    total = ((values - overall) ** 2).sum()
    return math.sqrt(between / total) if total > 0 else 0.0


