# Profile the quality issues by recruiter so the source of each problem is visible
def profile_quality(raw):
    """Count the main quality issues per recruiter (before cleaning)."""
    rows = []
    distance = pd.to_numeric(raw['distance_from_campus_km'], errors='coerce')
    q1, q3 = distance.quantile(0.25), distance.quantile(0.75)
    fence = q3 + 3.0 * (q3 - q1)
    for recruiter, part in raw.groupby('recruiter'):
        labels = sum((part[c].notna() & ~part[c].isin(allowed)).sum() for c, allowed in ALLOWED_VALUES.items())
        missing = int(part[EXPECTED_COLUMNS].isna().sum().sum())
        scores = sum(((part[c] < lo) | (part[c] > hi)).sum() for c, (lo, hi) in SCORE_LIMITS.items())
        extreme = int((part['distance_from_campus_km'] > fence).sum())
        rows += [{'Recruiter': recruiter, 'Issue': 'Non-standard or abbreviated labels', 'Cells': int(labels)},
                 {'Recruiter': recruiter, 'Issue': 'Missing cells', 'Cells': missing},
                 {'Recruiter': recruiter, 'Issue': 'Scores outside valid scale', 'Cells': int(scores)},
                 {'Recruiter': recruiter, 'Issue': 'Extreme distances', 'Cells': extreme}]
    return pd.DataFrame(rows)


