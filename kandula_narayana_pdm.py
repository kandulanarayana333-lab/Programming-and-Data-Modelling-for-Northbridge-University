class RecruiterDataLoader:
    """Load the recruiter extracts with identical, explicit parsing rules.

    Only empty cells are treated as missing. The text 'None' is preserved because it is a
    valid category in disability_status.
    """

    def __init__(self, csv_path, xlsx_path, sheet_name=0):
        self.csv_path = Path(csv_path)
        self.xlsx_path = Path(xlsx_path)
        self.sheet_name = sheet_name

    @staticmethod
    def _parsing_rules():
        return dict(keep_default_na=False, na_values=[''])

    def load_csv(self):
        frame = pd.read_csv(self.csv_path, dtype={c: str for c in TEXT_COLUMNS},
                            skipinitialspace=True, **self._parsing_rules())
        frame['source_file'] = self.csv_path.name
        return frame

    def load_excel(self):
        frame = pd.read_excel(self.xlsx_path, sheet_name=self.sheet_name, engine='openpyxl',
                              dtype={c: str for c in TEXT_COLUMNS}, **self._parsing_rules())
        frame['source_file'] = self.xlsx_path.name
        return frame


