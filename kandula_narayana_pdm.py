def distribution_figure(series, title, unit, bins=30):
    counts, edges = np.histogram(series, bins=bins)
    centres = (edges[:-1] + edges[1:]) / 2
    width = (edges[1] - edges[0]) * 0.94
    fig = go.Figure(go.Bar(
        x=centres, y=counts, width=width, text=counts, textposition='outside', textfont=dict(size=10), cliponaxis=False,
        marker=dict(color=counts, colorscale='Viridis', showscale=True, colorbar=dict(title='Applicants'),
                    line=dict(color='white', width=0.5)),
        customdata=np.stack([edges[:-1], edges[1:]], axis=1),
        hovertemplate=unit + ' %{customdata[0]:.1f} to %{customdata[1]:.1f}<br>Applicants: %{y:,}<extra></extra>'))
    mean_value, median_value = series.mean(), series.median()
    fig.add_vline(x=mean_value, line_dash='dash', line_color='#E63946', line_width=3,
                  annotation_text=f'Mean {mean_value:.1f}', annotation_position='top right', annotation_font_color='#E63946')
    fig.add_vline(x=median_value, line_dash='dot', line_color='#1D3557', line_width=3,
                  annotation_text=f'Median {median_value:.1f}', annotation_position='top left', annotation_font_color='#1D3557')
    style_figure(fig, title, f'Skewness {skew(series):.2f}; red dashed line is the mean, navy dotted line is the median')
    fig.update_xaxes(title=unit)
    fig.update_yaxes(title='Applicants', range=[0, counts.max() * 1.3])
    add_cmap_dropdown(fig, 'marker.colorscale')
    return fig


