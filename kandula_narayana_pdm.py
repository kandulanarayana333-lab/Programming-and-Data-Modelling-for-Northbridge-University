"""## Transparency: explaining individual predictions

An applicant who is not shortlisted may ask why, and the university must be able to answer in a way that is understandable and defensible. Both models can produce an **applicant-level explanation**.

- **XGBoost** uses its built-in contribution values (the contribution of each feature to the log-odds)
- **Naive Bayes** uses the log-likelihood ratio of each feature, which adds up exactly to the log-odds

For each explanation the contributions plus the starting point (the average log-odds of an offer) add up to the predicted probability. The cell **checks this sum against the model's own prediction**, so the explanation is guaranteed to be faithful. Positive bars push towards an offer and negative bars push away.
"""

def explain_applicant(student_id, model_name, top=10):
    """Explain one prediction as feature contributions in log-odds, verified against the model output."""
    row = X_all.loc[[student_id], FEATURES]
    pipeline = models[model_name]
    encoded = pipeline.named_steps['prep'].transform(row)
    names = [re.sub(r'^(numeric|categorical)__', '', n) for n in encoded.columns]
    if model_name == 'XGBoost':
        booster = pipeline.named_steps['model'].get_booster()
        contributions = booster.predict(xgb.DMatrix(encoded), pred_contribs=True, iteration_range=(0, best_round))[0]
        values, start = contributions[:-1], contributions[-1]
    else:
        classifier, x = pipeline.named_steps['model'], encoded.values[0]
        variance_1, variance_0 = classifier.var_[1], classifier.var_[0]
        values = -0.5 * np.log(variance_1 / variance_0) - 0.5 * ((x - classifier.theta_[1]) ** 2 / variance_1 - (x - classifier.theta_[0]) ** 2 / variance_0)
        start = np.log(classifier.class_prior_[1] / classifier.class_prior_[0])
    probability = 1 / (1 + np.exp(-(start + values.sum())))
    model_probability = pipeline.predict_proba(row)[0, 1]
    assert abs(probability - model_probability) < 1e-3, 'The explanation does not add up to the model prediction'

    def readable(name):
        if name in row.columns:
            return f'{name.replace("_", " ")} = {row[name].iloc[0]:.1f}'
        return f'{name.replace("_", " ")} (applies)'

    table = pd.DataFrame({'Feature': [readable(n) for n in names], 'Contribution': values})
    table = table[(table['Contribution'].abs() > 1e-9) | table['Feature'].str.contains('=')]
    table = table.reindex(table['Contribution'].abs().sort_values(ascending=False).index).head(top)
    return table, start, model_probability


